let changed = 0;
for (const cfg of langConfigs2) {
  const marker = cfg.marker;
  const idx = content.indexOf(marker);
  if (idx === -1) {
    console.log('NOT FOUND: ' + cfg.name);
    continue;
  }
  const lineEnd = content.indexOf('\n', idx);
  if (lineEnd === -1) continue;
  const before = content.slice(0, lineEnd + 1);
  const after = content.slice(lineEnd + 1);
  const contentToInsert = cfg.name === 'pt' ? pt : cfg.name === 'en' ? en : cfg.name === 'es' ? es : fr;
  content = before + contentToInsert + '\n' + after;
  changed++;
  console.log('Added fields for ' + cfg.name);
}

fs.writeFileSync(path, content, 'utf8');
console.log('Total languages updated:', changed);
