object AppLocalizer {
    fun getCatalog(selected: AppLanguage): StringsCatalog {
        return when (AppLanguage.resolveEffectiveLanguage(selected)) {
            AppLanguage.PT -> ptCatalog
            AppLanguage.ES -> esCatalog
            AppLanguage.FR -> frCatalog
            else -> enCatalog
        }
    }


    /**
     * Catalog used by non-Compose consumers (foreground media service, data
     * layer). Compose screens get the catalog through NoesisUiState, so this is
     * only a lookup helper kept in sync by NoesisViewModel.
     */
    @Volatile
    private var activeOverride: StringsCatalog? = null

    fun setActive(catalog: StringsCatalog) {
        activeOverride = catalog
    }

    fun active(): StringsCatalog = activeOverride ?: getCatalog(AppLanguage.SYSTEM)


