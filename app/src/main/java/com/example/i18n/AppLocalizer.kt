// ---------- Zone (Mental Spaces) content lookup ----------

/** Localized room title. Falls back to the stored DB title when unknown. */
fun StringsCatalog.zoneTitle(zoneId: String, fallback: String): String = when (zoneId) {
    "zone_emptiness" -> archRoomEmptiness
    "zone_identity" -> archRoomIdentity
    "zone_justice" -> archRoomJustice
    "zone_time" -> archRoomTime
    "zone_desire" -> archRoomDesire
    "zone_power" -> archRoomPower
    "zone_fear" -> archRoomFear
    else -> fallback
}

/** Localized room domain/subtitle. Falls back to the stored DB value. */
fun StringsCatalog.zoneDomain(zoneId: String, fallback: String): String =
    zoneDomains[zoneId] ?: fallback

/** Localized room architectural description. Falls back to the stored DB value. */
fun StringsCatalog.zoneDescription(zoneId: String, fallback: String): String =
    zoneDescriptions[zoneId] ?: fallback

/**
 * Localized sphere note for the known archetypes. Concepts created by the
 * user (CUSTOM key) keep the note stored with the concept itself.
 */
fun StringsCatalog.archetypeNote(archetypeKey: String, fallback: String): String =
    when (archetypeKey.uppercase(Locale.ROOT)) {
        "DESIRE" -> archetypeNoteDesire
        "FEAR" -> archetypeNoteFear
        "TIME" -> archetypeNoteTime
        "IDENTITY" -> archetypeNoteIdentity
        "JUSTICE" -> archetypeNoteJustice
        "DOMINATION" -> archetypeNoteDomination
        "POWER" -> archetypeNotePower
        "ANGER" -> archetypeNoteAnger
        "EMPTINESS" -> archetypeNoteEmptiness
        "CREATIVITY" -> archetypeNoteCreativity
        else -> fallback
    }

