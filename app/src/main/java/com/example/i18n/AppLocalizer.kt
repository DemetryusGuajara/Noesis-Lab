package com.example.i18n

import java.util.Locale

enum class AppLanguage(val code: String, val displayName: String, val nativeName: String) {
    SYSTEM("system", "System Default", "Padrão do Sistema"),
    PT("pt", "Portuguese", "Português"),
    EN("en", "English", "English"),
    ES("es", "Spanish", "Español"),
    FR("fr", "French", "Français");

    companion object {
        fun fromCode(code: String): AppLanguage {
            return entries.find { it.code.equals(code, ignoreCase = true) } ?: SYSTEM
        }

        fun resolveEffectiveLanguage(selected: AppLanguage): AppLanguage {
            if (selected != SYSTEM) return selected
            val sysLang = Locale.getDefault().language.lowercase()
            return when {
                sysLang.startsWith("pt") -> PT
                sysLang.startsWith("es") -> ES
                sysLang.startsWith("fr") -> FR
                else -> EN
            }
        }
    }
}

